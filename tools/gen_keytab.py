#!/usr/bin/env python3
"""LSX移植の src/M25TABLE.ASM から キー表(通常/SHIFT/CTRL)を取り出し hal/keytab.asm を作る。
表は 14列 x 8バイト。1列の並びは D7..D0 の順(添字 i ↔ EAh の D(7-i))。0=割り当てなし。
使い方: gen_keytab.py <M25TABLE.ASM> hal/keytab.asm"""
import re, sys
src = open(sys.argv[1], encoding='utf-8', errors='replace').read()
def table(name):
    m = re.search(r'^' + name + r':\s*\n((?:\s*DB[^\n]*\n)+)', src, re.M)
    vals = []
    for line in m.group(1).splitlines():
        body = line.split(';')[0].strip()[2:]
        vals += [int(x.strip().rstrip('H'), 16) for x in body.split(',') if x.strip()]
    assert len(vals) == 112, (name, len(vals))
    return vals
out = ['; generated by tools/gen_keytab.py from LSX-Dodgers M25TABLE.ASM (MIT). 14 columns x 8 bytes, D7..D0 order.',
       '        section code_user']
for nm, lab in (('KEY_TABLE', 'kb_tab_plain'), ('SHIFT_TABLE', 'kb_tab_shift'), ('CTRL_TABLE', 'kb_tab_ctrl')):
    out.append('        public  ' + lab)
    out.append(lab + ':')
    v = table(nm)
    for c in range(14):
        out.append('        defb    ' + ','.join('$%02X' % x for x in v[c * 8:c * 8 + 8]) + '    ; col %d' % c)
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print('wrote', sys.argv[2])
